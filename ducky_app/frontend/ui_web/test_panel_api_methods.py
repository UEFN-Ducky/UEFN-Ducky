def test_panel_api_public_methods() -> None:
    names = {
        n
        for n in dir(PanelApi)
        if not n.startswith('_') and callable(getattr(PanelApi, n, None))
    }
    missing = _PUBLIC_METHODS - names
    extra = names - _PUBLIC_METHODS
    assert not missing, f'missing PanelApi methods: {sorted(missing)}'
    assert not extra, f'unexpected PanelApi methods: {sorted(extra)}'

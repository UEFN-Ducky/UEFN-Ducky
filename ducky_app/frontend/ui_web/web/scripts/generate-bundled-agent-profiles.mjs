/**
 * Emit TypeScript mirror of frontend/bundled_agent_profiles.json.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, "..");
const srcJson = path.resolve(webRoot, "..", "..", "bundled_agent_profiles.json");
const outTs = path.join(webRoot, "src", "generated", "bundledAgentProfiles.ts");

const raw = JSON.parse(fs.readFileSync(srcJson, "utf8"));
const profiles = raw.profiles ?? [];

const tsBody = `/* AUTO-GENERATED by scripts/generate-bundled-agent-profiles.mjs — do not edit. */

export interface BundledAgentProfile {
  id: string;
  name: string;
  ducky_style: string;
  ducky_personality: string;
  when_to_use?: string;
  disabled_packs: string[];
  enabled_subskills?: Record<string, string[]>;
  disabled_tool_ids: string[];
  favorite_models: string[];
  kind?: "bundled";
}

export const BUNDLED_AGENT_PROFILES: BundledAgentProfile[] = ${JSON.stringify(
  profiles.map((p) => ({ ...p, kind: "bundled" })),
  null,
  2,
)};

export const BLANK_PROFILE_ID = "__blank__";
`;

fs.mkdirSync(path.dirname(outTs), { recursive: true });
fs.writeFileSync(outTs, tsBody, "utf8");
console.log(`Wrote ${profiles.length} bundled agent profiles -> ${path.relative(webRoot, outTs)}`);

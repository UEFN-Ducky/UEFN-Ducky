/**
 * Scan public/duckies/*.png and emit manifests for the React panel and Python backend.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, "..");
const publicDir = path.join(webRoot, "public", "duckies");
const outTs = path.join(webRoot, "src", "generated", "bundledDuckies.ts");
const outJson = path.resolve(webRoot, "..", "..", "bundled_duckies.json");

function slugFromFilename(filename) {
  return path.basename(filename, path.extname(filename)).toLowerCase();
}

function labelFromSlug(slug) {
  return slug
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function collectEntries() {
  if (!fs.existsSync(publicDir)) {
    return [];
  }
  const files = fs
    .readdirSync(publicDir)
    .filter((name) => name.toLowerCase().endsWith(".png"))
    .sort((a, b) => slugFromFilename(a).localeCompare(slugFromFilename(b)));

  return files.map((file) => {
    const id = slugFromFilename(file);
    return {
      id,
      label: labelFromSlug(id),
      file,
      url: `./duckies/${file}`,
    };
  });
}

const entries = collectEntries();
const defaultStyle = entries[0]?.id ?? "classic";

const tsBody = `/* AUTO-GENERATED by scripts/generate-bundled-duckies.mjs — do not edit. */

export interface BundledDucky {
  id: string;
  label: string;
  file: string;
  url: string;
}

export const BUNDLED_DUCKIES: BundledDucky[] = ${JSON.stringify(entries, null, 2)};

export const DEFAULT_BUNDLED_DUCKY_STYLE = ${JSON.stringify(defaultStyle)};
`;

const jsonBody = JSON.stringify(
  {
    default_style: defaultStyle,
    duckies: entries.map(({ id, label, file }) => ({ id, label, file })),
  },
  null,
  2,
);

fs.mkdirSync(path.dirname(outTs), { recursive: true });
fs.writeFileSync(outTs, tsBody, "utf8");
fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, jsonBody, "utf8");

console.log(`Wrote ${entries.length} bundled duckies -> ${path.relative(webRoot, outTs)}`);
console.log(`Wrote bundled_duckies.json (${defaultStyle} default)`);
